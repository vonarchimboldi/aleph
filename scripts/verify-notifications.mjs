import assert from 'node:assert/strict';
import {saveDay} from '../api/_math-diagnostic-store.js';
import {processFeedback,feedbackStatus} from '../api/_diagnostic-feedback.js';
import {listNotifications,markNotificationRead} from '../api/_notifications.js';
import handler from '../api/notifications.js';

process.env.ALEPH_DIAGNOSTIC_MEMORY='1';
const learner='notification-test-'+Date.now(),other=learner+'-other';
const draft=answer=>({answers:{'A1-1':{answer}},selected:[]});
const generate=async()=>({report:{headline:'Test report only'},model:'test-only'});
assert.deepEqual(await listNotifications(learner),{notifications:[],unreadCount:0});
let record=await saveDay({learner,day:1,expectedRevision:0,data:draft('Draft only')});
assert.equal((await listNotifications(learner)).notifications.length,0);
record=await saveDay({learner,day:1,expectedRevision:record.revision,action:'submit',data:draft('Submitted work')});
assert.equal((await listNotifications(learner)).notifications.length,0,'queued feedback is not a ready notification');
await processFeedback(learner,1,{generate});
let listed=await listNotifications(learner);assert.equal(listed.unreadCount,1);
const notice=listed.notifications[0];assert.equal(notice.day,1);assert.equal(notice.unread,true);
assert.equal(notice.href,`/math-diagnostic/?learner=${encodeURIComponent(learner)}&day=1#feedback`);
assert(!Object.hasOwn(notice,'report'),'notification list must not return learner answers/report bodies');
assert.deepEqual((await feedbackStatus(learner,1)).notification,{id:notice.id,version:notice.version});
assert.equal((await listNotifications(learner)).unreadCount,1,'listing does not consume notifications');
const ack=await markNotificationRead({learner,id:notice.id,version:notice.version});
assert.equal((await listNotifications(learner)).unreadCount,0);
assert.equal((await markNotificationRead({learner,id:notice.id,version:notice.version})).readAt,ack.readAt,'read acknowledgement is idempotent');
record=await saveDay({learner,day:1,expectedRevision:record.revision,data:draft('Later draft')});
assert.equal((await listNotifications(learner)).unreadCount,0,'a draft is not a new feedback version');
await saveDay({learner:other,day:1,expectedRevision:0,action:'submit',data:draft('Other learner')});await processFeedback(other,1,{generate});
assert.equal((await listNotifications(other)).unreadCount,1,'read markers are learner-specific');
await assert.rejects(markNotificationRead({learner:other,id:notice.id,version:notice.version}),e=>e.status===409);
record=await saveDay({learner,day:1,expectedRevision:record.revision,action:'submit',data:draft('Corrected submission')});
assert.equal((await listNotifications(learner)).notifications.length,0,'stale reports are not announced as ready');
await processFeedback(learner,1,{generate});listed=await listNotifications(learner);
assert.equal(listed.unreadCount,1);assert.equal(listed.notifications.length,1,'refresh replaces rather than duplicates the day');
assert.notEqual(listed.notifications[0].version,notice.version);
await assert.rejects(markNotificationRead({learner,id:notice.id,version:notice.version}),e=>e.status===409);
assert.equal((await listNotifications(learner)).unreadCount,1,'old acknowledgements cannot consume refreshed reports');

let status,payload,headers={};const response={setHeader(k,v){headers[k]=v},status(v){status=v;return this},json(v){payload=v;return this}};
await handler({method:'GET',url:'/api/notifications?learner='+learner,headers:{host:'localhost'}},response);assert.equal(status,200);assert.equal(payload.unreadCount,1);assert.equal(headers['Cache-Control'],'no-store');
await handler({method:'GET',url:'/api/notifications',headers:{host:'localhost'}},response);assert.equal(status,400);
await handler({method:'POST',body:{action:'delete',learner}},response);assert.equal(status,400);
await handler({method:'DELETE'},response);assert.equal(status,405);
const current=listed.notifications[0];await handler({method:'POST',body:{action:'read',learner,id:current.id,version:current.version}},response);assert.equal(status,200);assert.equal((await listNotifications(learner)).unreadCount,0);
console.log('PASS: ready-only notifications; no report-body disclosure; read-only listing; durable/version-specific idempotent reads; learner isolation; stale acknowledgement rejection; refresh deduplication; draft isolation; API validation. Test records only, no model calls.');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('app.js','utf8');
const context=vm.createContext({console,URL,selectedPatternMaterialId:null,pendingUploadFiles:new Map()});
for(const file of ['platinum-linear-algebra.js','platinum-machine-learning.js']) vm.runInContext(fs.readFileSync(file,'utf8'),context);
vm.runInContext(source.slice(0,source.indexOf('const state = loadState();'))+source.slice(source.indexOf('function loadState()')),context);
context.state={user:context.defaultUser(),...context.buildCoursePlan(),patternSubmissions:[]};
const days=context.dsaDataStructuresMonthDays();
const subject=context.state.subjects.find(s=>s.id==='subject-dsa-special-prep');
assert.equal(days.length,20);
assert.equal(days[0].date,'2026-10-05');assert.equal(days[19].date,'2026-10-30');
assert.equal(new Set(days.map(d=>d.id)).size,20);
for(let week=1;week<=4;week++)assert.equal(days.filter(d=>d.monthWeek===week).length,5);
assert(days.slice(0,5).every(d=>d.phase==='structure overview'));
assert(days.slice(5).every(d=>d.phase==='application and analysis'));
assert.equal(days.reduce((sum,d)=>sum+d.minutes,0),1800);
for(const day of days){
 assert(new Date(day.date+'T12:00:00Z').getUTCDay()>=1 && new Date(day.date+'T12:00:00Z').getUTCDay()<=5);
 const task=context.state.tasks.find(t=>t.id===`task-${day.id}`);
 const schedule=context.state.schedule.find(s=>s.id===`schedule-${day.id}`);
 assert(task && schedule);assert.equal(task.date,day.date);assert.equal(task.scheduleId,schedule.id);
 assert.equal(context.state.resources.filter(r=>r.id===`resource-${day.id}`).length,1);
 assert(fs.existsSync(decodeURIComponent(day.materialUrl)));
 const match=context.findPatternMaterialAcrossState(day.id);
 assert.equal(match.subject.id,subject.id);
 const feedback=context.buildFeedbackMaterialContext(match);
 assert.equal(feedback.questions.length,2);
 assert.equal(day.feedbackWorkflow.rubric.reduce((sum,r)=>sum+r.points,0),10);
}
assert(context.findPatternMaterial(subject,'dsa-special-prep-2026-09-day-01'));
const rendered=context.subjectReaderTemplate(subject);
assert(rendered.includes('October Week 1') && rendered.includes('October Week 4'));
for(const day of days)assert(rendered.includes(`data-solution-upload="${day.id}"`));
const saved=JSON.parse(JSON.stringify(context.state));
saved.tasks.find(t=>t.id===`task-${days[0].id}`).done=true;
saved.patternSubmissions=[{materialId:'dsa-special-prep-2026-09-day-01',solutionText:'Keep archived work'}];
const migrated=context.mergeCanonicalPlanWithProgress(context.buildCoursePlan(),saved);
assert(migrated.tasks.find(t=>t.id===`task-${days[0].id}`).done);
assert.deepEqual(migrated.patternSubmissions,saved.patternSubmissions);
assert(!context.buildCoursePlan(context.basicGateDaUser()).subjects.some(s=>s.id===subject.id));
console.log('PASS: 20 dated 90-minute sessions, four weekly workspaces, tasks/schedule/resources, feedback routing, archived material lookup, progress migration and Basic isolation.');

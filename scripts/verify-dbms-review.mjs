import assert from 'node:assert/strict';
import fs from 'node:fs';
import {DAY,emptyProgress,validateProgress,eligible,reviewQueue,rateCard,ankiTsv} from '../gate-da-dbms/review-core.mjs';
const deck=JSON.parse(fs.readFileSync('gate-da-dbms/cards.json','utf8'));
assert.equal(new Set(deck.map(c=>c.id)).size,deck.length);
assert.equal(new Set(deck.map(c=>c.recipe)).size,40);
for(let chapter=1;chapter<=8;chapter++)assert(deck.some(c=>c.chapter===chapter));
for(const card of deck)assert(card.front&&card.back&&card.recipe.match(/^R\d{2}$/));
const p=emptyProgress(),now=1000000;
assert.equal(reviewQueue(deck,p,now).length,0);
p.completed=[2];assert.equal(eligible(deck,p).length,0);
p.completed=[1];assert(eligible(deck,p).every(c=>c.chapter===1));
const initial=reviewQueue(deck,p,now);assert.equal(initial.length,2);
p.cards[initial[0].id]=rateCard({},'good',now);assert.equal(p.cards[initial[0].id].due,now+DAY);
p.cards[initial[1].id]=rateCard({},'again',now);assert.equal(p.cards[initial[1].id].due,now+60000);
assert(!reviewQueue(deck,p,now).some(c=>c.id===initial[1].id));
assert.equal(reviewQueue(deck,p,now+60000)[0].id,initial[1].id);
assert.equal(rateCard({},'easy',now).interval,4);
assert(rateCard({interval:7},'easy',now).interval>rateCard({interval:7},'hard',now).interval);
p.completed=[1,2,3,4,5,6,7,8];
for(const card of deck)p.cards[card.id]=rateCard({},'again',now);
assert.equal(reviewQueue(deck,p,now+60000).length,10);
assert.equal(validateProgress(JSON.parse(JSON.stringify(p)),deck).version,1);
assert.throws(()=>validateProgress({...p,completed:[9]},deck));
assert.throws(()=>validateProgress({...p,cards:{unknown:{due:now,interval:1}}},deck));
assert.throws(()=>validateProgress({...p,activeSession:{ids:['unknown'],index:0,chapter:1,reviewed:0}},deck));
const tsv=ankiTsv(deck);assert.equal(tsv.split('\n').length,deck.length+3);
console.log(`PASS: ${deck.length} cards, 40 recipes, unlocks, due priority, ratings, limits, backup validation and Anki export.`);
